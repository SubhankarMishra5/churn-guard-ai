"""Synthetic Telco-style customer data generator.

!!! SYNTHETIC DATA - FOR SOFTWARE TESTING ONLY !!!
The generated records are NOT real customers. Any model metrics obtained on this
data describe how well the pipeline recovers the *simulated* churn rule, not
real-world churn behaviour. Use the real IBM Telco dataset for genuine results.
"""
from __future__ import annotations

import argparse

import numpy as np
import pandas as pd

from config import settings
from config.schema import ADDON_COLS


def _sigmoid(x):
    return 1.0 / (1.0 + np.exp(-x))


def generate_synthetic_telco(n: int = 7043, seed: int = 42,
                             target_churn: float = 0.265,
                             n_duplicates: int = 15) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    pick = lambda opts, p: rng.choice(opts, size=n, p=p)

    senior = (rng.random(n) < 0.16).astype(int)
    partner = pick(["Yes", "No"], [0.48, 0.52])
    dependents = np.where(partner == "Yes", pick(["Yes", "No"], [0.40, 0.60]),
                          pick(["Yes", "No"], [0.08, 0.92]))
    contract = pick(["Month-to-month", "One year", "Two year"], [0.55, 0.21, 0.24])
    tenure = np.where(
        contract == "Month-to-month", rng.exponential(18, n) + 1,
        np.where(contract == "One year", rng.uniform(6, 72, n),
                 rng.uniform(24, 72, n)))
    tenure = np.clip(np.round(tenure), 1, 72).astype(int)

    phone = pick(["Yes", "No"], [0.90, 0.10])
    mult = np.where(phone == "No", "No phone service", pick(["Yes", "No"], [0.47, 0.53]))
    internet = pick(["DSL", "Fiber optic", "No"], [0.34, 0.44, 0.22])
    df = pd.DataFrame({
        "customerID": [f"SYN-{i:05d}" for i in range(n)],
        "gender": pick(["Female", "Male"], [0.5, 0.5]),
        "SeniorCitizen": senior, "Partner": partner, "Dependents": dependents,
        "tenure": tenure, "PhoneService": phone, "MultipleLines": mult,
        "InternetService": internet,
    })
    for col in ADDON_COLS:
        p_yes = 0.25 if col in ("OnlineSecurity", "TechSupport") else 0.40
        vals = np.where(rng.random(n) < p_yes, "Yes", "No")
        df[col] = np.where(internet == "No", "No internet service", vals)
    df["Contract"] = contract
    df["PaperlessBilling"] = pick(["Yes", "No"], [0.59, 0.41])
    df["PaymentMethod"] = pick(
        ["Electronic check", "Mailed check", "Bank transfer (automatic)",
         "Credit card (automatic)"], [0.34, 0.23, 0.22, 0.21])

    n_addons = sum((df[c] == "Yes").astype(int) for c in ADDON_COLS)
    base = np.where(internet == "Fiber optic", 55, np.where(internet == "DSL", 25, 0))
    monthly = (18.25 + (phone == "Yes") * 2 + base + n_addons * 5.5
               + (mult == "Yes") * 4 + rng.normal(0, 2.5, n))
    monthly = np.clip(monthly, 18.25, 118.75).round(2)
    df["MonthlyCharges"] = monthly
    df["TotalCharges"] = (monthly * tenure * rng.uniform(0.95, 1.05, n)).round(2)

    # Simulated churn rule (documented so users know what the models can learn).
    protected = (df["OnlineSecurity"] == "Yes") | (df["TechSupport"] == "Yes")
    logit = (1.5 * (contract == "Month-to-month") - 0.9 * (contract == "Two year")
             + 0.7 * (internet == "Fiber optic")
             + 0.5 * ((internet != "No") & ~protected)
             + 0.7 * (df["PaymentMethod"] == "Electronic check")
             + 0.3 * (df["PaperlessBilling"] == "Yes") + 0.3 * senior
             - 0.3 * (dependents == "Yes") - 0.035 * tenure
             + 0.012 * (monthly - 65) + rng.normal(0, 0.6, n))
    lo, hi = -10.0, 10.0
    for _ in range(60):                      # bisection on the intercept
        mid = (lo + hi) / 2
        if _sigmoid(logit + mid).mean() > target_churn:
            hi = mid
        else:
            lo = mid
    churn = rng.random(n) < _sigmoid(logit + (lo + hi) / 2)
    df["Churn"] = np.where(churn, "Yes", "No")

    # Realistic data-quality issues so the cleaning code is exercised.
    zero_idx = rng.choice(n, size=11, replace=False)
    df.loc[zero_idx, "tenure"] = 0
    df["TotalCharges"] = df["TotalCharges"].astype(object)
    df.loc[zero_idx, "TotalCharges"] = " "          # blank string, as in the real file
    dupes = df.sample(n_duplicates, random_state=seed)
    return pd.concat([df, dupes], ignore_index=True)


def save_synthetic(path=settings.SYNTH_DATA_PATH, **kwargs) -> pd.DataFrame:
    df = generate_synthetic_telco(**kwargs)
    path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(path, index=False)
    (path.parent / "README.txt").write_text(
        "SYNTHETIC DATA - NOT REAL CUSTOMERS.\n"
        "Generated by src/data_generation.py for software testing only.\n"
        "Schema mirrors the IBM Telco Customer Churn dataset.\n"
        "Metrics computed on this file must not be presented as real-world results.\n")
    return df


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--n", type=int, default=7043)
    ap.add_argument("--seed", type=int, default=42)
    a = ap.parse_args()
    d = save_synthetic(n=a.n, seed=a.seed)
    print(f"Wrote {len(d)} SYNTHETIC rows to {settings.SYNTH_DATA_PATH}")
